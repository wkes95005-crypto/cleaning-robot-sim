"""Generate the Webots supermarket world from the same grid map the 2D simulator uses.

    python3 webots/make_world.py   ->  webots/worlds/supermarket.wbt

Keeping the layout in sim/world.py as the single source means the 2D sim, Webots and (later) a
Gazebo .sdf export all describe the same floor.
"""
import os

from layout import ROOT, cell_to_xy, dirt_node, obstacle_node
from sim.world import CELL_M, DOCKS, H, W, World, ZONES, load_default_scenario, rect_cells

WORLDS = os.path.join(ROOT, "webots", "worlds")

FLEET = [  # id, controller, colour (same ids and dock order as the 2D sim)
    ("A1", "cleaner", "0.95 0.79 0.30"),
    ("M1", "cleaner", "0.31 0.55 1.0"),
    ("S1", "cleaner", "0.24 0.81 0.56"),
    ("S2", "cleaner", "0.24 0.81 0.56"),
]
ZONE_TINT = {"生鮮區": "0.55 0.68 0.5", "冷凍區": "0.6 0.7 0.78", "倉儲區": "0.62 0.58 0.52",
             "貨架A區": "0.72 0.68 0.6", "貨架B區": "0.72 0.68 0.6", "促銷區": "0.78 0.64 0.55",
             "收銀區": "0.6 0.6 0.66", "入口": "0.62 0.7 0.72", "充電站": "0.5 0.62 0.5"}
SHELVES = {(x, y) for x in (3, 6, 9, 12, 20, 23, 26, 29) for y in range(12, 21)}


def wall_kind(c, zone_of):
    x, y = c
    if x in (0, W - 1) or y in (0, H - 1) or (x == 33 and y <= 8) or (y == 8 and x >= 33):
        return "wall"
    if c in SHELVES:
        return "shelf"
    return {"生鮮區": "produce", "冷凍區": "freezer", "收銀區": "checkout"}.get(zone_of(c), "display")


STYLE = {  # height (m), colour
    "wall": (1.2, "0.82 0.82 0.8"),
    "shelf": (1.8, "0.55 0.38 0.24"),
    "produce": (0.85, "0.4 0.6 0.3"),
    "freezer": (1.0, "0.85 0.92 0.98"),
    "checkout": (0.9, "0.3 0.32 0.38"),
    "display": (1.0, "0.9 0.55 0.3"),
}


def box(name, x, y, z, sx, sy, sz, color, solid=True):
    shape = (f"Shape {{ appearance PBRAppearance {{ baseColor {color} roughness 0.8 metalness 0 }} "
             f"geometry Box {{ size {sx:.3f} {sy:.3f} {sz:.3f} }} }}")
    bound = f" boundingObject Box {{ size {sx:.3f} {sy:.3f} {sz:.3f} }}" if solid else ""
    return f"Solid {{ translation {x:.3f} {y:.3f} {z:.3f} children [ {shape} ] name \"{name}\"{bound} }}\n"


def runs(cells):
    """Merge cells into horizontal runs so the world has a few hundred boxes, not thousands."""
    out = []
    for y in sorted({c[1] for c in cells}):
        xs = sorted(c[0] for c in cells if c[1] == y)
        start = prev = xs[0]
        for x in xs[1:] + [None]:
            if x != prev + 1:
                out.append((start, prev, y))
                start = x
            prev = x if x is not None else prev
    return out


def build(console, dataset=False):
    """dataset=True: an empty store plus one camera rig running `dataset_maker`, which scatters random
    dirt and records labelled images for YOLO.
    console=False: each robot runs its own `cleaner` controller (phase 1).
    console=True: the FLEET supervisor runs the console and drives the robots; each robot only runs
    `camera_feed`, which publishes its camera to the dashboard."""
    world = World()
    load_default_scenario(world)
    parts = ['#VRML_SIM R2025b utf8\n',
             'EXTERNPROTO "../protos/CleaningRobot.proto"\n',
             'WorldInfo { info [ "Supermarket cleaning fleet (generated by make_world.py)" ] '
             'basicTimeStep 32 contactProperties [ ContactProperties { material2 "caster" coulombFriction [ 0 ] } ] }\n',
             'Viewpoint { orientation -0.3574 0.3574 0.8629 1.714 position 0 -17 17 }\n',
             'Background { skyColor [ 0.78 0.84 0.9 ] }\n',
             'DirectionalLight { direction -0.4 0.6 -1 intensity 2.2 castShadows TRUE }\n',
             'DirectionalLight { direction 0.5 -0.3 -1 intensity 0.8 }\n',
             box("floor", 0, 0, -0.05, W * CELL_M, H * CELL_M, 0.1, "0.74 0.74 0.72")]

    for name, (r, _) in ZONES.items():
        if name in ZONE_TINT:
            x0, y0, x1, y1 = r
            (ax, ay), (bx, by) = cell_to_xy((x0, y0)), cell_to_xy((x1, y1))
            parts.append(box(f"zone {name}", (ax + bx) / 2, (ay + by) / 2, 0.001,
                             (x1 - x0 + 1) * CELL_M, (y1 - y0 + 1) * CELL_M, 0.002, ZONE_TINT[name], solid=False))

    by_kind = {}
    for c in world.walls:
        by_kind.setdefault(wall_kind(c, world.zone_of), []).append(c)
    for kind, cells in by_kind.items():
        h, color = STYLE[kind]
        for i, (x0, x1, y) in enumerate(runs(cells)):
            (ax, ay), (bx, _) = cell_to_xy((x0, y)), cell_to_xy((x1, y))
            parts.append(box(f"{kind} {i}", (ax + bx) / 2, ay, h / 2, (x1 - x0 + 1) * CELL_M, CELL_M, h, color))

    for i, d in enumerate(DOCKS):
        x, y = cell_to_xy(d)
        parts.append(box(f"dock {i + 1}", x, y, 0.004, 0.45, 0.45, 0.006, "0.2 0.75 0.3", solid=False))

    for c, d in ({} if dataset else world.dirt).items():
        parts.append(dirt_node(c, d.kind) + "\n")
    for o in world.obstacles.values():
        parts.append(obstacle_node(o.id, o.kind, o.cell) + "\n")

    if dataset:
        parts.append('DEF RIG CleaningRobot { translation 0 0 0 name "rig" controller "dataset_maker" }\n')
    for (rid, ctrl, color), dock in zip([] if dataset else FLEET, DOCKS):
        x, y = cell_to_xy(dock)
        ctrl = "camera_feed" if console else ctrl
        parts.append(f'DEF {rid} CleaningRobot {{ translation {x:.3f} {y:.3f} 0 rotation 0 0 1 1.5708 '
                     f'name "{rid}" controller "{ctrl}" controllerArgs [ "{rid}" ] color {color} }}\n')
    if console:
        parts.append('DEF FLEET Robot { name "fleet console" controller "fleet_bridge" supervisor TRUE }\n')

    out = os.path.join(WORLDS, "dirt_dataset.wbt" if dataset else
                       "supermarket_console.wbt" if console else "supermarket.wbt")
    os.makedirs(WORLDS, exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("".join(parts))
    print(f"wrote {out}")


def main():
    build(console=False)
    build(console=True)
    build(console=False, dataset=True)


if __name__ == "__main__":
    main()
